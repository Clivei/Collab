"""Emit src/mold_nora_gemini_data.js from the traced OXDOG mould used by NORA Gemini (v2).
Run: python3 gen_gemini_data.py   (reads ../v2/gemini_v2_data.py, writes mm coordinates)"""
import json, os
here = os.path.dirname(os.path.abspath(__file__))
ns = {}
exec(open(os.path.join(here, '..', 'v2', 'gemini_v2_data.py')).read(), ns)
pair = lambda a: [[round(a[i] / 10, 1), round(a[i + 1] / 10, 1)] for i in range(0, len(a), 2)]
hol = ns['HOL']
holes = [[round(hol[i] / 10, 1), round(hol[i + 1] / 10, 1), round(hol[i + 2] / 10, 1)] for i in range(0, len(hol), 3)]
logo = [[[p[i], p[i + 1]] for i in range(0, len(p), 2)] for p in ns['LOGO']]
out = {'OUT': pair(ns['OUT']), 'WR': pair(ns['WR']), 'WC': pair(ns['WC']), 'HOLES': holes, 'LOGO': logo}
js = '/* generated by gen_gemini_data.py - traced OXDOG mould (mm). x = lateral, y = distance from butt. */\n'
js += 'const NORA_GEMINI_DATA = ' + json.dumps(out, separators=(',', ':')) + ';\n'
open(os.path.join(here, 'src', 'mold_nora_gemini_data.js'), 'w').write(js)
print(len(js), 'bytes', len(holes), 'holes')
